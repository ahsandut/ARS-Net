"""Training entry point for ARS-Net.

Training and validation records must be subject-disjoint. Centerline and distance targets are generated by datasets/target_generation.py and returned by the dataset loader.
"""
from __future__ import annotations

import argparse
import json
import random
import sys
from pathlib import Path

import numpy as np
import torch
from torch.utils.data import DataLoader

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from datasets.dataset import KneeLigamentDataset, load_manifest, validate_subject_splits
from losses.segmentation_losses import ARSNetLoss, LossWeights
from models import ARSNet


def seed_everything(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)
    torch.backends.cudnn.benchmark = False
    torch.backends.cudnn.deterministic = True


def parse_args():
    p = argparse.ArgumentParser()
    p.add_argument("--manifest", required=True, help="CSV manifest")
    p.add_argument("--image-root", default=".")
    p.add_argument("--output-dir", default="outputs/ars_net")
    p.add_argument("--image-size", type=int, default=320, help="Square model input size; use 320 for manuscript experiments")
    p.add_argument("--epochs", type=int, default=150)
    p.add_argument("--batch-size", type=int, default=4)
    p.add_argument("--lr", type=float, default=2e-4)
    p.add_argument("--weight-decay", type=float, default=1e-4)
    p.add_argument("--warmup-epochs", type=int, default=5)
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--workers", type=int, default=4)
    p.add_argument("--amp", action="store_true")
    p.add_argument("--resume", default=None)
    p.add_argument("--architecture-variant", choices=["full", "no_arrm", "no_msfm", "no_arrm_no_msfm"], default="full")
    p.add_argument("--loss-variant", choices=["L1", "L2", "L3", "L4"], default="L4",
                   help="L1=segmentation; L2=segmentation+distance; L3=segmentation+centerline; L4=full objective")
    return p.parse_args()


def main():
    args = parse_args()
    seed_everything(args.seed)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    rows = load_manifest(args.manifest)
    validate_subject_splits(rows)
    train_ds = KneeLigamentDataset(args.manifest, "train", args.image_root, image_size=args.image_size, augment=True, seed=args.seed)
    val_ds = KneeLigamentDataset(args.manifest, "val", args.image_root, image_size=args.image_size, augment=False, seed=args.seed)
    train_subjects = {r["subject_id"] for r in train_ds.rows}
    val_subjects = {r["subject_id"] for r in val_ds.rows}
    if train_subjects & val_subjects:
        raise RuntimeError("Subject leakage between train and validation.")
    train_loader = DataLoader(train_ds, batch_size=args.batch_size, shuffle=True,
                              num_workers=args.workers, pin_memory=device.type == "cuda")
    val_loader = DataLoader(val_ds, batch_size=args.batch_size, shuffle=False,
                            num_workers=args.workers, pin_memory=device.type == "cuda")

    model = ARSNet(input_size=args.image_size, architecture_variant=args.architecture_variant).to(device)
    # Loss ablation definitions from the manuscript: L1 segmentation only;
    # L2 adds distance supervision; L3 adds centerline supervision; L4 uses both.
    loss_weights = {
        "L1": LossWeights(centerline=0.0, distance=0.0),
        "L2": LossWeights(centerline=0.0, distance=0.2),
        "L3": LossWeights(centerline=0.3, distance=0.0),
        "L4": LossWeights(centerline=0.3, distance=0.2),
    }[args.loss_variant]
    criterion = ARSNetLoss(loss_weights)
    optimizer = torch.optim.AdamW(model.parameters(), lr=args.lr, weight_decay=args.weight_decay)
    scaler = torch.cuda.amp.GradScaler(enabled=args.amp and device.type == "cuda")
    start_epoch, best_val = 0, float("inf")

    if args.resume:
        ckpt = torch.load(args.resume, map_location=device)
        model.load_state_dict(ckpt["model_state"])
        optimizer.load_state_dict(ckpt["optimizer_state"])
        start_epoch = int(ckpt.get("epoch", 0))
        best_val = float(ckpt.get("best_val_loss", best_val))

    out = Path(args.output_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "run_config.json").write_text(json.dumps(vars(args), indent=2), encoding="utf-8")

    # Linear warm-up followed by cosine decay, matching the manuscript schedule.
    def lr_factor(epoch):
        if epoch < args.warmup_epochs:
            return float(epoch + 1) / max(1, args.warmup_epochs)
        progress = (epoch - args.warmup_epochs) / max(1, args.epochs - args.warmup_epochs)
        return 0.5 * (1.0 + np.cos(np.pi * min(progress, 1.0)))
    scheduler = torch.optim.lr_scheduler.LambdaLR(optimizer, lr_lambda=lr_factor)

    for epoch in range(start_epoch, args.epochs):
        model.train()
        train_losses = []
        for batch in train_loader:
            image = batch["image"].to(device, non_blocking=True)
            mask = batch["mask"].to(device, non_blocking=True)
            targets = {
                "mask": mask,
                "centerline": batch["centerline"].to(device, non_blocking=True),
                "distance": batch["distance"].to(device, non_blocking=True),
            }
            optimizer.zero_grad(set_to_none=True)
            with torch.cuda.amp.autocast(enabled=args.amp and device.type == "cuda"):
                outputs = model(image)
                losses = criterion(outputs, targets)
            scaler.scale(losses["total"]).backward()
            scaler.unscale_(optimizer)
            torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            scaler.step(optimizer)
            scaler.update()
            train_losses.append(float(losses["total"].detach().cpu()))

        model.eval()
        val_losses = []
        with torch.no_grad():
            for batch in val_loader:
                image = batch["image"].to(device)
                mask = batch["mask"].to(device)
                outputs = model(image)
                targets = {
                    "mask": mask,
                    "centerline": batch["centerline"].to(device),
                    "distance": batch["distance"].to(device),
                }
                losses = criterion(outputs, targets)
                val_losses.append(float(losses["total"].cpu()))
        scheduler.step()
        val_loss = float(np.mean(val_losses))
        state = {
            "epoch": epoch + 1, "model_state": model.state_dict(),
            "optimizer_state": optimizer.state_dict(), "best_val_loss": best_val,
            "args": vars(args),
        }
        torch.save(state, out / "last.pt")
        if val_loss < best_val:
            best_val = val_loss
            torch.save(state, out / "best.pt")
        print(f"Epoch {epoch+1}/{args.epochs}: train={np.mean(train_losses):.5f} val={val_loss:.5f}")


if __name__ == "__main__":
    main()
